#!/usr/bin/env python3
"""Admixture-fraction sensitivity: one simulation config per panel x fraction.

Copies each panel's simulation config (simulations/config/<base>.yaml) and
changes only the coyote admixture fraction, the experiment name and out_dir.
The seed is unchanged, so every fraction uses the same simulation seeds and
differences come from the admixture fraction alone.

    python3 sensitivity/admixture/make_configs.py     # from the repository root

Writes sensitivity/admixture/configs/<panel>_f<frac>.yaml and
sensitivity/admixture/grid.tsv (panel, fraction, sim config, real-data
window_stats dir, model out_dir).
"""
import os
import yaml

HERE = "sensitivity/admixture"
FRACTIONS = [0.10, 0.20, 0.30, 0.40, 0.48, 0.60, 0.70, 0.80]
PANELS = {   # panel: (base simulation config, real-data window_stats)
    "historical":   ("simulations/config/final_53g.yaml",        "results/rw_hist_safe_53g/data/window_stats"),
    "museum_early": ("simulations/config/museum_early_53g.yaml", "results/rw_museum_early_53g/data/window_stats"),
    "museum_late":  ("simulations/config/museum_late_53g.yaml",  "results/rw_museum_late_53g/data/window_stats"),
    # 13 historical (1975) wolves without SAFE, and the 2 SAFE wolves on their own
    "hist1975":     ("simulations/config/hist1975_53g.yaml",     "results/rw_hist1975_53g/data/window_stats"),
    "safe2":        ("simulations/config/safe2_53g.yaml",        "results/rw_safe2_53g/data/window_stats"),
}

os.makedirs(f"{HERE}/configs", exist_ok=True)
rows = ["panel\tfraction\tconfig\treal_window_stats\tmodel_dir"]
for panel, (base, real) in PANELS.items():
    for f in FRACTIONS:
        cfg = yaml.safe_load(open(base))
        tag = f"{panel}_f{f:.2f}"
        cfg["experiment"]["name"] = tag
        cfg["out_dir"] = f"{HERE}/results/{tag}"
        cfg["demography"]["admixture_fraction"] = f
        path = f"{HERE}/configs/{tag}.yaml"
        with open(path, "w") as fh:
            fh.write(f"# {tag}: generated by {HERE}/make_configs.py from {base};\n"
                     f"# identical except demography.admixture_fraction = {f}, experiment.name and out_dir.\n")
            yaml.safe_dump(cfg, fh, sort_keys=False)
        rows.append(f"{panel}\t{f:.2f}\t{path}\t{real}\t{cfg['out_dir']}")
open(f"{HERE}/grid.tsv", "w").write("\n".join(rows) + "\n")
print(f"{len(rows) - 1} configs written to {HERE}/configs/")
